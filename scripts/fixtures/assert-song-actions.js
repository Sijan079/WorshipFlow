(async () => {
  const results = [];
  const wait = () => new Promise(resolve => setTimeout(resolve, 180));
  const assert = (ok, label) => { if (!ok) throw new Error(label); results.push(label); };
  const button = label => [...document.querySelectorAll("button")].find(el => el.getAttribute("aria-label") === label || el.textContent.trim() === label);
  button("Load short song").click(); await wait();
  const editor = document.querySelector(".ProseMirror");
  const focusFirst = async () => {
    editor.focus(); const range = document.createRange(); range.setStart(editor.querySelector(".song-lyric-line").firstChild, 1); range.collapse(true);
    const sel = window.getSelection(); sel.removeAllRanges(); sel.addRange(range); document.dispatchEvent(new Event("selectionchange")); await wait();
  };
  const key = async (target, value, modifiers = {}) => {
    target.dispatchEvent(new KeyboardEvent("keydown", { key: value, bubbles: true, cancelable: true, ...modifiers })); await wait();
  };
  const viewer = document.querySelector("[data-song-viewport]");
  const viewerHeight = viewer.getBoundingClientRect().height;
  const exportButton = button("Export DOCX");
  exportButton.focus(); exportButton.blur();
  viewer.dispatchEvent(new MouseEvent("click", { bubbles: true, cancelable: true }));
  await key(document.body, "k", { ctrlKey: true });
  assert(document.querySelector('[data-shortcut-mode="true"]'), "Ctrl+K activates after clicking blank viewer space");
  assert(Math.abs(viewer.getBoundingClientRect().height - viewerHeight) < 1, "Shortcut overlay does not resize the viewer");
  assert([...document.querySelectorAll(".song-lyric-line")].at(-1).hasAttribute("data-shortcut-target"), "First activation targets the bottom-most line");
  assert(getComputedStyle(document.querySelector('[data-shortcut-overlay] [role="status"]')).boxShadow.includes("0px 0px 16px"), "Shortcut overlay has floating elevation");
  const shortcutGuide = document.querySelector('[data-shortcut-overlay]').textContent;
  assert(shortcutGuide.includes("Caret") && shortcutGuide.includes("Section"), "Shortcut guide distinguishes caret and section movement");
  assert(document.querySelector('[data-shortcut-target]').getBoundingClientRect().top >= document.querySelector('[data-shortcut-overlay]').getBoundingClientRect().bottom, "Restored target is visible below the overlay");
  await key(editor, "d");
  assert((document.getElementById("fixture-text").textContent.match(/\[Chorus\]/g) || []).length === 2, "Shortcut duplicates the fallback section");
  assert(document.querySelector('[data-shortcut-mode="true"]'), "Shortcut mode stays active after an action");
  button("Undo").click(); await wait();
  await focusFirst();
  assert(editor.querySelector(".song-lyric-line").hasAttribute("data-shortcut-target"), "Selecting another line moves the shortcut target");
  const beforePlainArrow = document.getElementById("fixture-text").textContent;
  await key(editor, "ArrowDown");
  assert(document.getElementById("fixture-text").textContent === beforePlainArrow, "Plain arrows do not reorder sections");
  await focusFirst();
  await key(editor, "ArrowDown", { altKey: true });
  assert(document.getElementById("fixture-text").textContent.startsWith("[Chorus]"), "Alt+Down moves the active section");
  assert(document.querySelector('[data-shortcut-target]')?.closest('[data-song-section]')?.textContent.includes("Verse"), "Section movement preserves the active lyric in the moved section");
  button("Undo").click(); await wait(); await focusFirst();
  const beforeRepeat = document.getElementById("fixture-text").textContent;
  await key(editor, "ArrowDown", { altKey: true, repeat: true });
  assert(document.getElementById("fixture-text").textContent === beforeRepeat, "Held Alt+Arrow does not repeat section movement");
  exportButton.focus();
  await key(exportButton, "ArrowDown", { altKey: true });
  assert(document.getElementById("fixture-text").textContent === beforeRepeat, "Section movement is scoped to editor focus");
  await focusFirst();
  await key(editor, "t");
  assert(document.querySelector('[role="menu"][aria-label="Tag section"]'), "Shortcut opens the compact tag popover");
  assert(document.querySelector('[role="menuitemradio"][aria-checked="true"]')?.textContent.includes("Verse"), "Tag popover marks the current tag");
  button("Bridge").click(); await wait(); await wait();
  assert(document.getElementById("fixture-text").textContent.startsWith("[Bridge]"), "Tag shortcut preserves selection and applies the chosen tag");
  assert(document.querySelector('[data-shortcut-mode="true"]'), "Applying a tag keeps shortcut mode active");
  await key(editor, "c");
  await key(editor, "v");
  assert((document.getElementById("fixture-text").textContent.match(/\[Bridge\]/g) || []).length === 2, "Copy and paste shortcuts clone the active section");
  assert(document.querySelector('[data-shortcut-mode="true"]'), "Copy and paste keep shortcut mode active");
  button("Undo").click(); await wait();
  await key(editor, "t");
  await key(document.activeElement, "Escape");
  assert(!document.querySelector('[role="menu"][aria-label="Tag section"]') && document.querySelector('[data-shortcut-mode="true"]'), "First Escape closes only the tag popover");
  await wait(); await key(editor, "Escape");
  assert(document.querySelector('[data-shortcut-mode="false"]'), "Second Escape exits shortcut mode");
  await focusFirst();
  const rect = editor.querySelector(".song-lyric-line").getBoundingClientRect();
  editor.dispatchEvent(new MouseEvent("contextmenu", { button: 2, clientX: rect.left + 5, clientY: rect.top + 5, bubbles: true, cancelable: true })); await wait();
  const items = [...document.querySelectorAll('[role="menuitem"]')];
  assert(items.some(el => el.textContent.includes("Tag section")), "Right-click song actions are enabled by default");
  assert(!items.some(el => el.textContent.trim() === "Verse"), "Tags are nested rather than flat");
  for (const label of ["Copy section", "Paste section after", "Insert section after", "Split section", "Merge with previous section", "Duplicate section", "Move section up", "Move section down", "Delete section"]) {
    const item = items.find(el => el.textContent.includes(label));
    assert(item?.querySelector("svg") && item.querySelector("kbd"), `${label} displays its icon and shortcut`);
  }
  assert(items.find(el => el.textContent.includes("Move section down"))?.querySelector("kbd")?.textContent.includes("Alt"), "Move action displays its Alt+Arrow shortcut");
  const tag = items.find(el => el.textContent.includes("Tag section"));
  tag.focus(); tag.dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowRight", bubbles: true, cancelable: true })); await wait();
  assert([...document.querySelectorAll('[role="menuitem"]')].some(el => el.textContent.trim() === "Verse"), "Tag submenu supports keyboard opening");
  document.activeElement.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true, cancelable: true })); await wait();
  document.activeElement.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true, cancelable: true })); await wait();
  const card = document.querySelector('[class*="controls"]');
  assert(getComputedStyle(card).boxShadow.includes("0px 0px 16px"), "Control card has all-sided elevation");
  assert(getComputedStyle(document.querySelector('[aria-label="Song Editor"]')).overflow === "visible", "Control shadow is not clipped by the editor");
  return results;
})()
