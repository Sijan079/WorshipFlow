// Run at a desktop viewport >=1500px with agent-browser eval --stdin.
(async () => {
  const results = [];
  const wait = () => new Promise(resolve => setTimeout(resolve, 180));
  const assert = (condition, label) => { if (!condition) throw new Error(label); results.push(label); };
  const button = label => [...document.querySelectorAll("button")].find(node => node.getAttribute("aria-label") === label || node.textContent.trim() === label);
  const region = document.querySelector('[aria-label="Song Editor"]');
  const editor = document.querySelector(".ProseMirror");
  const text = () => document.getElementById("fixture-text").textContent;
  const zoom = async value => {
    const picker = document.querySelector('[role="combobox"][aria-label="Document zoom"]');
    picker.dispatchEvent(new PointerEvent("pointerdown", { button: 0, pointerType: "mouse", bubbles: true, cancelable: true }));
    await wait();
    const option = [...document.querySelectorAll('[role="option"]')].find(node => node.textContent.trim() === `${value}%`);
    option.focus();
    option.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", bubbles: true, cancelable: true }));
    await wait(); await wait();
  };
  const select = async (start, end = start) => {
    editor.focus();
    const range = document.createRange();
    range.setStart(start.firstChild, 0);
    range.setEnd(end.firstChild, end === start ? 0 : end.textContent.length);
    window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
    document.dispatchEvent(new Event("selectionchange"));
    await wait();
  };
  if (document.querySelector('nav[aria-label="Song sections"]')) button("Toggle section outline").click();
  button("Load sample song").click(); await wait();
  region.style.width = "1350px";
  await wait();
  const original = text();
  const pageCount = new Set([...editor.querySelectorAll('[data-song-page]')].map(node => node.dataset.songPage)).size;
  assert(!region.querySelector("footer"), "Footer removed");
  assert(region.querySelector('[aria-label="Document controls"] [aria-label="Document zoom"]'), "Zoom is in top controls");
  assert(getComputedStyle(region).borderTopWidth === "0px", "Viewer has no enclosing card border");
  await zoom(75);
  assert(region.dataset.pageColumns === "2", "75% fits two editable pages");
  const page1 = editor.querySelector('[data-song-page="1"]');
  const page2 = editor.querySelector('[data-song-page="2"]');
  assert(page2.getBoundingClientRect().left > page1.getBoundingClientRect().left + 500, "Second page is beside the first");
  assert(editor.contentEditable === "true", "Two-page document remains editable");
  assert([...editor.querySelectorAll('[data-song-page]')].every(line => {
    const rect = line.getBoundingClientRect();
    const root = editor.getBoundingClientRect();
    const page = Number(line.dataset.songPage) - 1;
    const y = (rect.top - root.top) / 0.75 - Math.floor(page / 2) * 1080;
    return y >= 95 && y + rect.height / 0.75 <= 961;
  }), "All two-page lyrics stay within margins");
  const leftLast = [...editor.querySelectorAll('[data-song-page="1"]')].filter(node => node.textContent).at(-1);
  const rightFirst = [...editor.querySelectorAll('[data-song-page="2"]')].find(node => node.textContent);
  await select(leftLast, rightFirst);
  assert(window.getSelection().toString().includes(rightFirst.textContent), "Native selection crosses left and right pages");
  document.execCommand("insertText", false, "Cross-page replacement"); await wait();
  assert(text().includes("Cross-page replacement"), "Cross-page replacement edits one document");
  button("Undo").click(); await wait();
  assert(text() === original, "Undo restores cross-page replacement");
  await select(editor.querySelector('[data-song-page="2"]'));
  document.execCommand("insertText", false, "Right-page edit "); await wait();
  assert(text().includes("Right-page edit"), "Typing works on right-hand page");
  await zoom(100);
  assert(region.dataset.pageColumns === "1", "Zooming in returns to one column");
  button("Undo").click(); await wait();
  assert(text() === original, "Zoom does not add an undo step");
  await zoom(75);
  button("Toggle section outline").click(); await wait(); await wait();
  assert(region.dataset.pageColumns === "1", "Open outline falls back to one column when width is insufficient");
  button("Toggle section outline").click(); await wait(); await wait();
  assert(region.dataset.pageColumns === "2", "Closing outline restores two columns");
  region.style.width = "900px"; await wait(); await wait();
  assert(region.dataset.pageColumns === "1", "Narrow viewer falls back without changing zoom");
  assert(document.querySelector('[aria-label="Document zoom"]').textContent.includes("75%"), "Width fallback preserves chosen zoom");
  region.style.width = "1350px"; await wait();
  await zoom(50);
  assert(region.dataset.pageColumns === "2", "50% supports two columns");
  assert(new Set([...editor.querySelectorAll('[data-song-page]')].map(node => node.dataset.songPage)).size === pageCount, "Zoom preserves page count");
  assert(text() === original, "Layout changes preserve exported lyrics");
  button("Load short song").click(); await wait(); await wait();
  assert(region.dataset.pageColumns === "1", "Single-page song uses one column");
  region.style.width = "";
  await zoom(75);
  button("Load sample song").click(); await wait();
  return results;
})()
