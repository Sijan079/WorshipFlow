// Run in the verification fixture with: agent-browser eval --stdin < this-file.
(async () => {
  const results = [];
  const wait = () => new Promise(resolve => setTimeout(resolve, 100));
  const assert = (condition, label) => { if (!condition) throw new Error(label); results.push(label); };
  const button = label => [...document.querySelectorAll("button")].find(node => node.getAttribute("aria-label") === label || node.textContent.trim() === label);
  const text = () => document.getElementById("fixture-text").textContent;
  const editor = () => document.querySelector(".ProseMirror");
  const select = async (start, startOffset, end = start, endOffset = startOffset) => {
    editor().focus();
    const range = document.createRange();
    range.setStart(start.firstChild || start, startOffset);
    range.setEnd(end.firstChild || end, endOffset);
    const selection = window.getSelection();
    selection.removeAllRanges(); selection.addRange(range);
    document.dispatchEvent(new Event("selectionchange"));
    await wait();
  };
  button("Load sample song").click();
  await wait(); await wait();
  assert(new Set([...document.querySelectorAll("[data-song-page]")].map(node => node.dataset.songPage)).size >= 3, "Long songs paginate");
  const pageTop = editor().getBoundingClientRect().top;
  const inPage = [...document.querySelectorAll(".song-lyric-line")].every(line => {
    const rect = line.getBoundingClientRect();
    const y = (rect.top - pageTop) % 1080;
    return y >= 95 && y + rect.height <= 961;
  });
  assert(inPage, "Lyrics stay inside page margins");
  const original = text();
  const lines = [...document.querySelectorAll(".song-lyric-line")].filter(node => node.textContent);
  await select(lines[2], 2, lines[lines.length - 2], 4);
  assert(window.getSelection().toString().includes("Praise the Lord 10"), "Selection crosses page gaps");
  assert(text() === original, "Pagination and selection do not change lyrics");
  button("Load short song").click();
  await wait();
  let lyrics = [...document.querySelectorAll(".song-lyric-line")];
  await select(lyrics[3], 0);
  editor().dispatchEvent(new KeyboardEvent("keydown", { key: "Backspace", code: "Backspace", keyCode: 8, bubbles: true, cancelable: true }));
  await wait();
  assert(text() === "[Verse]\nAlpha\nBeta\nGamma\n[Chorus]\nDelta\nEpsilon", "Backspace preserves section boundary");
  lyrics = [...document.querySelectorAll(".song-lyric-line")];
  await select(lyrics[0], 5);
  document.execCommand("insertText", false, " edited");
  await wait();
  assert(text().includes("Alpha edited"), "Native typing updates structured lyrics");
  editor().dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", code: "Enter", keyCode: 13, bubbles: true, cancelable: true }));
  await wait();
  document.execCommand("insertText", false, "New line");
  await wait();
  assert(text().includes("Alpha edited\nNew line\nBeta"), "Enter inserts a lyric line");
  button("Undo").click(); await wait();
  assert(!text().includes("New line"), "Undo reverts typing");
  button("Redo").click(); await wait();
  assert(text().includes("New line"), "Redo restores typing");
  // The tag picker must preserve the editor selection while it has focus.
  lyrics = [...document.querySelectorAll(".song-lyric-line")];
  await select(lyrics[0], 2, lyrics[1], 3);
  const tagPicker = document.querySelector('[role="combobox"][aria-label="Section tag"]');
  tagPicker.dispatchEvent(new PointerEvent("pointerdown", { button: 0, pointerType: "mouse", bubbles: true, cancelable: true }));
  await wait();
  const bridge = [...document.querySelectorAll('[role="option"]')].find(node => node.textContent.trim() === "Bridge");
  assert(bridge, "Tag picker opens from selected lyrics");
  bridge.focus();
  bridge.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", code: "Enter", keyCode: 13, bubbles: true, cancelable: true }));
  await wait();
  assert(text().startsWith("[Bridge]\nAlpha edited\nNew line\n[Verse]\nBeta"), "Toolbar tags selected whole lines");
  const data = new DataTransfer();
  data.setData("text/plain", "<img src=x onerror=alert(1)>\nPasted lyric");
  data.setData("text/html", '<img src=x onerror="alert(1)"><b>Pasted lyric</b>');
  editor().dispatchEvent(new ClipboardEvent("paste", { clipboardData: data, bubbles: true, cancelable: true }));
  await wait();
  assert(text().includes("Pasted lyric") && !editor().querySelector("img,b"), "Paste keeps text and discards HTML");
  button("Toggle section outline").click(); await wait();
  assert(document.querySelector('nav[aria-label="Song sections"]'), "Section outline opens");
  button("Export DOCX").click(); await wait(); await wait();
  assert(document.getElementById("fixture-export").textContent === "DOCX generated", "DOCX generation works with edited text");
  assert([...document.querySelectorAll('[role="status"]')].some(node => node.textContent === "Saved on this device"), "Draft is saved on this device");
  return results;
})()
